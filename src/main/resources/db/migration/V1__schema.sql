-- Fachschema Buchungsservice (Stufe 1). Portabel für H2 (MODE=PostgreSQL) und PostgreSQL.

CREATE TABLE kreditor (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kreditorennummer VARCHAR(50)  NOT NULL,
    name             VARCHAR(200) NOT NULL,
    CONSTRAINT uk_kreditor_kreditorennummer UNIQUE (kreditorennummer)
);

CREATE TABLE debitor (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vorname             VARCHAR(100) NOT NULL,
    nachname            VARCHAR(100) NOT NULL,
    geburtsdatum        DATE         NOT NULL,
    plz                 VARCHAR(10)  NOT NULL,
    dublettenschluessel VARCHAR(500) NOT NULL,
    CONSTRAINT uk_debitor_dublettenschluessel UNIQUE (dublettenschluessel)
);

CREATE TABLE forderungskonto (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aktenzeichen VARCHAR(50)    NOT NULL,
    kreditor_id  BIGINT         NOT NULL,
    saldo        NUMERIC(15, 2) NOT NULL DEFAULT 0,
    version      BIGINT         NOT NULL,
    CONSTRAINT uk_forderungskonto_aktenzeichen UNIQUE (aktenzeichen),
    CONSTRAINT fk_forderungskonto_kreditor FOREIGN KEY (kreditor_id) REFERENCES kreditor (id)
);
CREATE INDEX ix_forderungskonto_kreditor ON forderungskonto (kreditor_id);

CREATE TABLE konto_debitor (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    konto_id       BIGINT                   NOT NULL,
    debitor_id     BIGINT                   NOT NULL,
    zugeordnet_am  TIMESTAMP WITH TIME ZONE NOT NULL,
    zugeordnet_von VARCHAR(100)             NOT NULL,
    CONSTRAINT uk_konto_debitor UNIQUE (konto_id, debitor_id),
    CONSTRAINT fk_konto_debitor_konto FOREIGN KEY (konto_id) REFERENCES forderungskonto (id),
    CONSTRAINT fk_konto_debitor_debitor FOREIGN KEY (debitor_id) REFERENCES debitor (id)
);
CREATE INDEX ix_konto_debitor_debitor ON konto_debitor (debitor_id);

CREATE TABLE buchung (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    konto_id          BIGINT                   NOT NULL,
    art               VARCHAR(20)              NOT NULL,
    betrag            NUMERIC(15, 2)           NOT NULL,
    valuta            DATE                     NOT NULL,
    buchungszeit      TIMESTAMP WITH TIME ZONE NOT NULL,
    client_request_id VARCHAR(100)             NOT NULL,
    request_hash      CHAR(64)                 NOT NULL,
    kreditor_id       BIGINT,
    debitor_id        BIGINT,
    storno_von_id     BIGINT,
    grund             VARCHAR(30),
    bemerkung         VARCHAR(500),
    ausloeser         VARCHAR(100),
    CONSTRAINT uk_buchung_client_request_id UNIQUE (client_request_id),
    -- Eine Buchung kann höchstens einmal storniert werden (Doppelstorno auch auf DB-Ebene ausgeschlossen).
    CONSTRAINT uk_buchung_storno_von UNIQUE (storno_von_id),
    CONSTRAINT ck_buchung_betrag_positiv CHECK (betrag > 0),
    CONSTRAINT ck_buchung_art CHECK (art IN ('HAUPTFORDERUNG', 'ZINSEN', 'GEBUEHREN', 'ZAHLUNG', 'AUSBUCHUNG', 'STORNO')),
    CONSTRAINT ck_buchung_kreditor CHECK ((art IN ('HAUPTFORDERUNG', 'ZINSEN', 'GEBUEHREN')) = (kreditor_id IS NOT NULL)),
    CONSTRAINT ck_buchung_debitor CHECK ((art = 'ZAHLUNG') = (debitor_id IS NOT NULL)),
    CONSTRAINT ck_buchung_storno_von CHECK ((art = 'STORNO') = (storno_von_id IS NOT NULL)),
    CONSTRAINT ck_buchung_grund CHECK ((art IN ('STORNO', 'AUSBUCHUNG')) = (grund IS NOT NULL)),
    CONSTRAINT ck_buchung_ausloeser CHECK ((art IN ('STORNO', 'AUSBUCHUNG')) = (ausloeser IS NOT NULL)),
    CONSTRAINT ck_buchung_bemerkung CHECK (bemerkung IS NULL OR art IN ('STORNO', 'AUSBUCHUNG')),
    CONSTRAINT fk_buchung_konto FOREIGN KEY (konto_id) REFERENCES forderungskonto (id),
    CONSTRAINT fk_buchung_kreditor FOREIGN KEY (kreditor_id) REFERENCES kreditor (id),
    CONSTRAINT fk_buchung_debitor FOREIGN KEY (debitor_id) REFERENCES debitor (id),
    CONSTRAINT fk_buchung_storno_von FOREIGN KEY (storno_von_id) REFERENCES buchung (id)
);
CREATE INDEX ix_buchung_konto ON buchung (konto_id);
CREATE INDEX ix_buchung_kreditor ON buchung (kreditor_id);
CREATE INDEX ix_buchung_debitor ON buchung (debitor_id);

CREATE TABLE verrechnung (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    art                 VARCHAR(20)              NOT NULL,
    haben_buchung_id    BIGINT                   NOT NULL,
    soll_buchung_id     BIGINT                   NOT NULL,
    betrag              NUMERIC(15, 2)           NOT NULL,
    zeitpunkt           TIMESTAMP WITH TIME ZONE NOT NULL,
    aufhebung_von_id    BIGINT,
    ausgeloest_durch_id BIGINT,
    -- Eine Verrechnung kann höchstens einmal aufgehoben werden.
    CONSTRAINT uk_verrechnung_aufhebung_von UNIQUE (aufhebung_von_id),
    CONSTRAINT ck_verrechnung_betrag_positiv CHECK (betrag > 0),
    CONSTRAINT ck_verrechnung_art CHECK (art IN ('VERRECHNUNG', 'AUFHEBUNG')),
    CONSTRAINT ck_verrechnung_aufhebung_von CHECK ((art = 'AUFHEBUNG') = (aufhebung_von_id IS NOT NULL)),
    CONSTRAINT ck_verrechnung_ausgeloest_durch CHECK ((art = 'AUFHEBUNG') = (ausgeloest_durch_id IS NOT NULL)),
    CONSTRAINT fk_verrechnung_haben FOREIGN KEY (haben_buchung_id) REFERENCES buchung (id),
    CONSTRAINT fk_verrechnung_soll FOREIGN KEY (soll_buchung_id) REFERENCES buchung (id),
    CONSTRAINT fk_verrechnung_aufhebung_von FOREIGN KEY (aufhebung_von_id) REFERENCES verrechnung (id),
    CONSTRAINT fk_verrechnung_ausgeloest_durch FOREIGN KEY (ausgeloest_durch_id) REFERENCES buchung (id)
);
CREATE INDEX ix_verrechnung_haben ON verrechnung (haben_buchung_id);
CREATE INDEX ix_verrechnung_soll ON verrechnung (soll_buchung_id);
CREATE INDEX ix_verrechnung_ausgeloest_durch ON verrechnung (ausgeloest_durch_id);
